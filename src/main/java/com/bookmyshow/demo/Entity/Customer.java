package com.bookmyshow.demo.Entity;

import jakarta.persistence.*;

@Entity
@Table(name = "customer",uniqueConstraints = {@UniqueConstraint(name = "uk_cutomer_phone",columnNames = "phoneno"),
        @UniqueConstraint(name = "uk_cutomer_email",columnNames = "email")
})
public class Customer {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private long id;
    private String name;
    @Column(nullable = false,length = 200)
    private String email;
    @Column(nullable = false,length = 200)
    private String phoneno;

    public Customer(String name, String email, String phoneno) {
        this.name = name;
        this.email = email;
        this.phoneno = phoneno;
    }

    public Customer() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhoneno() {
        return phoneno;
    }

    public void setPhoneno(String phoneno) {
        this.phoneno = phoneno;
    }

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }
}


















































































































































































































































































































































































































































































































































